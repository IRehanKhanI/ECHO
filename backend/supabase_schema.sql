create extension if not exists vector;

create table if not exists public.earth_analogs (
    id bigint generated by default as identity primary key,
    location_name text not null,
    country text not null,
    lat double precision not null,
    lng double precision not null,
    min_temp_c double precision not null,
    slope_deg double precision not null,
    feature_vector vector(2) not null,
    unique (location_name, country)
);

create or replace function public.match_earth_analogs(
    query_embedding vector(2),
    match_count integer
)
returns table (
    id bigint,
    location_name text,
    country text,
    lat double precision,
    lng double precision,
    min_temp_c double precision,
    slope_deg double precision,
    cosine_distance double precision
)
language sql
stable
as $$
    select
        analog.id,
        analog.location_name,
        analog.country,
        analog.lat,
        analog.lng,
        analog.min_temp_c,
        analog.slope_deg,
        analog.feature_vector <=> query_embedding as cosine_distance
    from public.earth_analogs as analog
    order by analog.feature_vector <=> query_embedding
    limit greatest(match_count, 0);
$$;
